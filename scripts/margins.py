#!/usr/bin/env python3
"""Derive per-concern noise margins from the stability scans, then test them.

  python3 scripts/margins.py            # print margins and the stability tables
  python3 scripts/margins.py --write    # also write public/margins.js (the numbers the app uses)

Rule, fixed before any variant was scanned: a concern's margin is the largest absolute change in its raw
score across the ORDINARY variants of face s2 (dim, warm, tilt; the identical photo scanned twice differs
by under 0.01), with a floor of 2 points. Stress variants (blur, crop, JPEG) are reported, never used.
Faces s1 and s3 are a holdout: margins are never fitted to them.

The verdict code below is written from the README rules, like recheck.py, not ported from verdict.js.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHOPPABLE = ["acne", "age_spot", "dark_circle_v2", "eye_bag", "firmness", "moisture",
             "oiliness", "pore", "radiance", "redness", "texture", "wrinkle"]
CUTS = {"moisture": (50, 65)}
DEFAULT = (65, 80)
FLOOR = 2
TEST_FACES = ["h1", "h2"]  # test-only portraits: never sample faces, never used for the margins
ORDINARY = ["dim", "warm", "tilt"]
STRESS = ["blur", "crop", "jpeg"]

products = json.loads((ROOT / "public/products.json").read_text())


def scores(face, variant=None):
    variant = "base" if variant is None and face in TEST_FACES else variant
    path = ROOT / (f"public/personas/{face}/scores.json" if variant is None else f"public/stability/{face}/{variant}.json")
    return {k: v["raw"] for k, v in json.loads(path.read_text())["concerns"].items()}


def verdict(raw, targets, margins=None):
    usable = sorted((raw[k] - CUTS.get(k, DEFAULT)[0], k) for k in set(targets) if isinstance(raw.get(k), (int, float)))
    if not usable:
        return "inconclusive"
    _, k = usable[0]
    v, (weak, fine) = raw[k], CUTS.get(k, DEFAULT)
    if margins is not None and min(abs(v - weak), abs(v - fine)) < margins[k]:
        return "close"
    return "match" if v < weak else "partial" if v < fine else "skip"


def margins_from(face="s2"):
    base = scores(face)
    return {k: round(max(FLOOR, max(abs(scores(face, v)[k] - base[k]) for v in ORDINARY)), 1) for k in SHOPPABLE}


M = margins_from()
print("margins (points):", M, "\n")


def table(face, variants, label):
    base = scores(face)
    rows = []
    for v in variants:
        var = scores(face, v)
        flips = caught = 0
        for p in products:
            b0 = verdict(base, p["targets"])
            if b0 != verdict(var, p["targets"]):
                flips += 1
                caught += verdict(base, p["targets"], M) == "close"
        rows.append((v, flips, caught))
    abst = sum(verdict(base, p["targets"], M) == "close" for p in products)
    print(f"{face} {label}: abstentions at baseline {abst}/12")
    for v, f, c in rows:
        print(f"   {v:5} flips without band {f:2}/12, flagged 'close' by band {c}")
    return rows, abst


tot = {"flips": 0, "caught": 0, "scans": 0}
for face in ("s2", "s1", "s3", *TEST_FACES):
    rows, _ = table(face, [v for v in ORDINARY if (ROOT / f"public/stability/{face}/{v}.json").exists()], "ordinary")
    if face != "s2":  # holdout only
        tot["flips"] += sum(f for _, f, _ in rows)
        tot["caught"] += sum(c for *_, c in rows)
        tot["scans"] += len(rows)
table("s2", STRESS, "stress")
print(f"\nHOLDOUT (s1, s3, {', '.join(TEST_FACES)}; ordinary): {tot['flips']} verdict flips across {tot['scans']} variant scans; the band flagged {tot['caught']} of them in advance")
if "--write" in sys.argv:
    (ROOT / "public/margins.js").write_text("// Generated by scripts/margins.py from the stability scans. Do not edit.\nexport const MARGINS = " + json.dumps(M) + ";\n")
    print("wrote public/margins.js")
